#!/usr/bin/env node
// Generate the TypeScript types of the HTTP contracts with openapi-typescript:
//   packages/api/openapi.yaml                  -> packages/api/src/schema.d.ts
//   packages/pricing-api/openapi-pricing.yaml  -> packages/pricing-api/src/schema.d.ts
// `--check` regenerates in memory and fails when a committed file differs (contract drift, CI).
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const targets = [
  { spec: path.join(root, "packages", "api", "openapi.yaml"), out: path.join(root, "packages", "api", "src", "schema.d.ts") },
  {
    spec: path.join(root, "packages", "pricing-api", "openapi-pricing.yaml"),
    out: path.join(root, "packages", "pricing-api", "src", "schema.d.ts"),
  },
];
const check = process.argv.includes("--check");
const header =
  "/**\n * Generated by `npm run api:gen` from the OpenAPI file next to this package. Do not edit by hand.\n */\n\n";

let drift = false;
for (const { spec, out } of targets) {
  // defaultNonNullable off: a field with a `default` stays optional (clients may omit it in requests).
  const ast = await openapiTS(pathToFileURL(spec), { alphabetize: false, exportType: false, defaultNonNullable: false });
  const text = (header + astToString(ast)).replace(/\r\n/g, "\n");
  const rel = path.relative(root, out).split(path.sep).join("/");
  if (check) {
    const current = await readFile(out, "utf8").catch(() => "");
    if (current.replace(/\r\n/g, "\n") !== text) {
      drift = true;
      console.error(`[api:gen] ${rel} is out of date with its OpenAPI file. Run \`npm run api:gen\` and commit.`);
    } else {
      console.log(`[api:gen] ${rel} up to date`);
    }
  } else {
    await writeFile(out, text, "utf8");
    console.log(`[api:gen] wrote ${rel}`);
  }
}
if (drift) process.exit(1);
